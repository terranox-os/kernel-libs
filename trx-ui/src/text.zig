    data[0x7C - 0x20] = .{ 0x00, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x00, 0x00, 0x00, 0x00, 0x00 };
    // 0x7D '}'
    data[0x7D - 0x20] = .{ 0x00, 0x70, 0x18, 0x18, 0x18, 0x0E, 0x18, 0x18, 0x18, 0x18, 0x70, 0x00, 0x00, 0x00, 0x00, 0x00 };
    // 0x7E '~'
    data[0x7E - 0x20] = .{ 0x00, 0x00, 0x00, 0x00, 0x76, 0xDC, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };

    break :blk data;
};

/// Get the glyph bitmap for a character.
/// Returns a pointer to 16 bytes (one per row), or null for unsupported chars.
pub fn getGlyph(char: u8) ?*const [16]u8 {
    if (char < FIRST_CHAR or char > LAST_CHAR) return null;
    return &font_data[char - FIRST_CHAR];
}

/// Measure the pixel width of a string at the given font_size.
/// Scale factor = font_size / GLYPH_H.  Each character is GLYPH_W * scale wide.
pub fn measureTextWidth(str: []const u8, font_size: u16) f32 {
    const scale: f32 = @as(f32, @floatFromInt(font_size)) / @as(f32, @floatFromInt(GLYPH_H));
    const char_w: f32 = @as(f32, @floatFromInt(GLYPH_W)) * scale;
    return char_w * @as(f32, @floatFromInt(str.len));
}

/// Render a single glyph into a pixel buffer.
///
/// `buf` is a row-major ARGB32 buffer of `stride` pixels per row.
/// Draws the glyph at pixel position (px, py) using the given colour
/// and integer scale factor.
pub fn renderGlyph(
    buf: []u32,
    stride: u32,
    px: i32,
    py: i32,
    char: u8,
    scale: u32,
    fg: Color,
) void {
    const glyph = getGlyph(char) orelse return;
    const fg_packed = fg.toArgb32();

    var row: u32 = 0;
    while (row < GLYPH_H) : (row += 1) {
        const bits = glyph[row];
        var col: u32 = 0;
        while (col < GLYPH_W) : (col += 1) {
            if (bits & (@as(u8, 0x80) >> @intCast(col)) != 0) {
                // Fill scale x scale block
                var sy: u32 = 0;
                while (sy < scale) : (sy += 1) {
                    var sx: u32 = 0;
                    while (sx < scale) : (sx += 1) {
                        const bx = px + @as(i32, @intCast(col * scale + sx));
                        const by = py + @as(i32, @intCast(row * scale + sy));
                        if (bx >= 0 and by >= 0) {
                            const ubx: u32 = @intCast(bx);
                            const uby: u32 = @intCast(by);
                            const idx = uby * stride + ubx;
                            if (idx < buf.len) {
                                buf[idx] = fg_packed;
                            }
                        }
                    }
                }
            }
        }
    }
}

/// Render a string into a pixel buffer at (px, py).
pub fn renderText(
    buf: []u32,
    stride: u32,
    px: i32,
    py: i32,
    str: []const u8,
    font_size: u16,
    fg: Color,
) void {
    const scale: u32 = @max(1, font_size / GLYPH_H);
    const char_w: i32 = @intCast(GLYPH_W * scale);
    var x = px;
    for (str) |ch| {
        renderGlyph(buf, stride, x, py, ch, scale, fg);
        x += char_w;
    }
}

/// Measure text with word wrapping.  Returns (width, height) of the
/// bounding box when the text wraps at `max_width` pixels.
pub fn measureTextWrapped(str: []const u8, font_size: u16, max_width: f32) struct { w: f32, h: f32 } {
    const scale: f32 = @as(f32, @floatFromInt(font_size)) / @as(f32, @floatFromInt(GLYPH_H));
    const char_w: f32 = @as(f32, @floatFromInt(GLYPH_W)) * scale;
    const line_h: f32 = @as(f32, @floatFromInt(font_size));

    if (str.len == 0) return .{ .w = 0, .h = 0 };
    if (max_width <= 0) return .{ .w = measureTextWidth(str, font_size), .h = line_h };

    var lines: u32 = 1;
    var line_w: f32 = 0;
    var widest: f32 = 0;

    for (str) |ch| {
        if (ch == '\n') {
            if (line_w > widest) widest = line_w;
            line_w = 0;
            lines += 1;
            continue;
        }
        line_w += char_w;
        if (line_w > max_width) {
            if (line_w - char_w > widest) widest = line_w - char_w;
            line_w = char_w; // current char moves to new line
            lines += 1;
        }
    }
    if (line_w > widest) widest = line_w;

    return .{ .w = widest, .h = line_h * @as(f32, @floatFromInt(lines)) };
}

/// Render text with word wrapping into a pixel buffer.
pub fn renderTextWrapped(
    buf: []u32,
    stride: u32,
    px: i32,
    py: i32,
    str: []const u8,
    font_size: u16,
    fg: Color,
    max_width: u32,
) void {
    const scale: u32 = @max(1, font_size / GLYPH_H);
    const char_w: u32 = GLYPH_W * scale;
    const line_h: i32 = @intCast(font_size);

    var x: i32 = px;
    var y: i32 = py;

    for (str) |ch| {
        if (ch == '\n') {
            x = px;
            y += line_h;
            continue;
        }

        // Wrap if exceeding max_width
        if (max_width > 0 and @as(u32, @intCast(@max(0, x - px))) + char_w > max_width) {
            x = px;
            y += line_h;
        }

        renderGlyph(buf, stride, x, y, ch, scale, fg);
        x += @intCast(char_w);
    }
}

// ── Tests ──────────────────────────────────────────────────────────

const testing = @import("std").testing;

test "measureTextWidth basic" {
    // At font_size 16 (scale=1), each char is 8px wide
    const w = measureTextWidth("Hello", 16);
    try testing.expectEqual(@as(f32, 40), w);
}

test "measureTextWidth scaled" {
    // At font_size 32 (scale=2), each char is 16px wide
    const w = measureTextWidth("AB", 32);
    try testing.expectEqual(@as(f32, 32), w);
}

test "getGlyph returns data for printable ASCII" {
    try testing.expect(getGlyph('A') != null);
    try testing.expect(getGlyph(' ') != null);
    try testing.expect(getGlyph('~') != null);
}

test "getGlyph returns null for control chars" {
    try testing.expectEqual(@as(?*const [16]u8, null), getGlyph(0x00));
    try testing.expectEqual(@as(?*const [16]u8, null), getGlyph(0x1F));
}

test "renderGlyph writes pixels" {
    var buf: [16 * 16]u32 = [_]u32{0} ** (16 * 16);
    renderGlyph(&buf, 16, 0, 0, 'A', 1, Color.WHITE);
    // 'A' glyph row 2 = 0x18 => pixels at cols 3,4
    try testing.expect(buf[2 * 16 + 3] != 0);
    try testing.expect(buf[2 * 16 + 4] != 0);
    // Row 0 of 'A' is 0x00 => all blank
    try testing.expectEqual(@as(u32, 0), buf[0]);
}

test "renderText draws multiple chars" {
    var buf: [16 * 32]u32 = [_]u32{0} ** (16 * 32);
    renderText(&buf, 32, 0, 0, "AB", 16, Color.WHITE);
    // 'A' at x=0, 'B' at x=8. Check 'B' glyph row 2 = 0x7C => col 1 set
    const b_row2 = 2 * 32 + 8 + 1; // y=2, x=8+1=9
    try testing.expect(buf[b_row2] != 0);
}

test "all 95 printable ASCII glyphs present" {
    var ch: u8 = 0x20;
    while (ch <= 0x7E) : (ch += 1) {
        try testing.expect(getGlyph(ch) != null);
    }
}

test "newly added glyphs are non-blank" {
    // Spot-check some previously missing glyphs
    const g_glyph = getGlyph('G').?;
    var has_pixels = false;
    for (g_glyph) |row| {
        if (row != 0) has_pixels = true;
    }
    try testing.expect(has_pixels);

    const v_glyph = getGlyph('v').?;
    has_pixels = false;
    for (v_glyph) |row| {
        if (row != 0) has_pixels = true;
    }
    try testing.expect(has_pixels);
}

test "measureTextWrapped single line fits" {
    const result = measureTextWrapped("Hello", 16, 200);
    try testing.expectEqual(@as(f32, 40), result.w);
    try testing.expectEqual(@as(f32, 16), result.h);
}

test "measureTextWrapped wraps text" {
    // 10 chars * 8px = 80px. Max width = 50 → wraps after 6 chars
    const result = measureTextWrapped("0123456789", 16, 50);
    try testing.expectEqual(@as(f32, 48), result.w); // 6 chars fit
    try testing.expect(result.h > 16); // at least 2 lines
}

test "measureTextWrapped explicit newline" {
    const result = measureTextWrapped("AB\nCD", 16, 200);
    try testing.expectEqual(@as(f32, 16), result.w); // max line is 2 chars
    try testing.expectEqual(@as(f32, 32), result.h); // 2 lines
}

test "renderTextWrapped wraps at boundary" {
    // 4 chars at 8px each = 32px. max_width=20 → wraps after 2 chars
    // Need buffer tall enough for 2 lines (32 rows) at stride 32
    var buf: [32 * 32]u32 = [_]u32{0} ** (32 * 32);
    renderTextWrapped(&buf, 32, 0, 0, "ABCD", 16, Color.WHITE, 20);
    // 'C' should be at y=16 (second line), x=0
    // 'C' glyph row 2 = 0x3C => cols 2-5 set
    const c_row2 = (16 + 2) * 32 + 2; // y=18, x=2
    try testing.expect(buf[c_row2] != 0);
}
