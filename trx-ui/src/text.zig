/// Get the glyph bitmap for a character.
/// Returns a pointer to 16 bytes (one per row), or null for unsupported chars.
pub fn getGlyph(char: u8) ?*const [16]u8 {
    if (char < FIRST_CHAR or char > LAST_CHAR) return null;
    return &font_data[char - FIRST_CHAR];
}

/// Measure the pixel width of a string at the given font_size.
/// Scale factor = font_size / GLYPH_H.  Each character is GLYPH_W * scale wide.
pub fn measureTextWidth(str: []const u8, font_size: u16) f32 {
    const scale: f32 = @as(f32, @floatFromInt(font_size)) / @as(f32, @floatFromInt(GLYPH_H));
    const char_w: f32 = @as(f32, @floatFromInt(GLYPH_W)) * scale;
    return char_w * @as(f32, @floatFromInt(str.len));
}

/// Render a single glyph into a pixel buffer.
///
/// `buf` is a row-major ARGB32 buffer of `stride` pixels per row.
/// Draws the glyph at pixel position (px, py) using the given colour
/// and integer scale factor.
pub fn renderGlyph(
    buf: []u32,
    stride: u32,
    px: i32,
    py: i32,
    char: u8,
    scale: u32,
    fg: Color,
) void {
    const glyph = getGlyph(char) orelse return;
    const fg_packed = fg.toArgb32();

    var row: u32 = 0;
    while (row < GLYPH_H) : (row += 1) {
        const bits = glyph[row];
        var col: u32 = 0;
        while (col < GLYPH_W) : (col += 1) {
            if (bits & (@as(u8, 0x80) >> @intCast(col)) != 0) {
                // Fill scale x scale block
                var sy: u32 = 0;
                while (sy < scale) : (sy += 1) {
                    var sx: u32 = 0;
                    while (sx < scale) : (sx += 1) {
                        const bx = px + @as(i32, @intCast(col * scale + sx));
                        const by = py + @as(i32, @intCast(row * scale + sy));
                        if (bx >= 0 and by >= 0) {
                            const ubx: u32 = @intCast(bx);
                            const uby: u32 = @intCast(by);
                            const idx = uby * stride + ubx;
                            if (idx < buf.len) {
                                buf[idx] = fg_packed;
                            }
                        }
                    }
                }
            }
        }
    }
}

/// Render a string into a pixel buffer at (px, py).
pub fn renderText(
    buf: []u32,
    stride: u32,
    px: i32,
    py: i32,
    str: []const u8,
    font_size: u16,
    fg: Color,
) void {
    const scale: u32 = @max(1, font_size / GLYPH_H);
    const char_w: i32 = @intCast(GLYPH_W * scale);
    var x = px;
    for (str) |ch| {
        renderGlyph(buf, stride, x, py, ch, scale, fg);
        x += char_w;
    }
}

// ── Tests ──────────────────────────────────────────────────────────

const testing = @import("std").testing;

test "measureTextWidth basic" {
    // At font_size 16 (scale=1), each char is 8px wide
    const w = measureTextWidth("Hello", 16);
    try testing.expectEqual(@as(f32, 40), w);
}

test "measureTextWidth scaled" {
    // At font_size 32 (scale=2), each char is 16px wide
    const w = measureTextWidth("AB", 32);
    try testing.expectEqual(@as(f32, 32), w);
}

test "getGlyph returns data for printable ASCII" {
    try testing.expect(getGlyph('A') != null);
    try testing.expect(getGlyph(' ') != null);
    try testing.expect(getGlyph('~') != null);
}

test "getGlyph returns null for control chars" {
    try testing.expectEqual(@as(?*const [16]u8, null), getGlyph(0x00));
    try testing.expectEqual(@as(?*const [16]u8, null), getGlyph(0x1F));
}

test "renderGlyph writes pixels" {
    var buf: [16 * 16]u32 = [_]u32{0} ** (16 * 16);
    renderGlyph(&buf, 16, 0, 0, 'A', 1, Color.WHITE);
    // 'A' glyph row 2 = 0x18 => pixels at cols 3,4
    try testing.expect(buf[2 * 16 + 3] != 0);
    try testing.expect(buf[2 * 16 + 4] != 0);
    // Row 0 of 'A' is 0x00 => all blank
    try testing.expectEqual(@as(u32, 0), buf[0]);
}

test "renderText draws multiple chars" {
    var buf: [16 * 32]u32 = [_]u32{0} ** (16 * 32);
    renderText(&buf, 32, 0, 0, "AB", 16, Color.WHITE);
    // 'A' at x=0, 'B' at x=8. Check 'B' glyph row 2 = 0x7C => col 1 set
    const b_row2 = 2 * 32 + 8 + 1; // y=2, x=8+1=9
    try testing.expect(buf[b_row2] != 0);
}
